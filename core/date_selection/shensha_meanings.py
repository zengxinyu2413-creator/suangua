# 等级权重（供综合评分参考；引擎已自有分，此为释义层呈现）
_LEVEL_WEIGHT = {"上吉": 3, "大吉": 2, "吉": 1, "小吉": 0.5,
                 "大凶": -3, "凶": -2, "小凶": -1}


def explain(name: str) -> Dict[str, Any]:
    """取单一神煞释义；未收录者返回基本占位（不杜撰宜忌）。"""
    e = SHENSHA.get(name)
    if e:
        return {"name": name, **e, "weight": _LEVEL_WEIGHT.get(e["level"], 0)}
    return {"name": name, "type": "", "level": "", "meaning": "", "yi": [], "ji": [], "weight": 0}


def annotate_day(ji_shen: List[str], xiong_sha: List[str]) -> Dict[str, Any]:
    """为一日之吉神/凶煞列表补释义，并归纳该日宜忌总集（去重）。"""
    ji_ex = [explain(n) for n in (ji_shen or []) if n and n != "无"]
    xiong_ex = [explain(n) for n in (xiong_sha or []) if n and n != "无"]
    yi_set, ji_set = [], []
    for e in ji_ex:
        for s in e.get("yi", []):
            if s not in yi_set:
                yi_set.append(s)
    for e in xiong_ex:
        for s in e.get("ji", []):
            if s not in ji_set:
                ji_set.append(s)
    # 收录率（监控释义覆盖）
    known = sum(1 for e in ji_ex + xiong_ex if e.get("level"))
    total = len(ji_ex) + len(xiong_ex)
    return {
        "ji_shen_explained": ji_ex,
        "xiong_sha_explained": xiong_ex,
        "shensha_yi": yi_set,
        "shensha_ji": ji_set,
        "coverage": {"known": known, "total": total},
    }


