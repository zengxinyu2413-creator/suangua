def synthesize_shensha_for_purpose(ji_shen: List[str], xiong_sha: List[str],
                                   purpose: str) -> Dict[str, Any]:
    """据所择之事，判定该日神煞中利此事之吉神、忌此事之凶煞，合成专属断语。
    返回 {support:[{name,meaning}], against:[{name,meaning}], net, verdict}。"""
    # 别名归一化：常用同义词 → 规范 purpose 键，免简写落通用默认、拿不到专属断。
    _ALIAS = {
        "婚礼": "结婚", "完婚": "结婚", "迎娶": "嫁娶", "出嫁": "嫁娶", "娶亲": "嫁娶",
        "提亲": "订婚", "定亲": "订婚",
        "开张": "开业", "开工": "开业", "开店": "开业", "营业": "开业",
        "下葬": "安葬", "出殡": "安葬", "落葬": "安葬", "葬礼": "安葬",
        "乔迁": "搬家", "迁居": "搬家", "搬迁": "搬家", "移居": "搬家", "入伙": "入宅",
        "远行": "出行", "旅行": "出行", "出差": "出行", "外出": "出行",
        "看病": "求医", "治病": "求医", "就医": "求医", "手术": "求医",
        "兴工": "动土", "破木": "破土", "盖房": "修造", "建房": "修造", "装修": "修造",
        "赴任": "上任", "履新": "上任", "就职": "上任",
        "求财": "纳财", "进财": "纳财", "买卖": "交易",
    }
    purpose = _ALIAS.get(purpose, purpose)
    kws = PURPOSE_KEYWORDS.get(purpose, [purpose])
    ann = annotate_day(ji_shen, xiong_sha)

    def _hit(items_key, ex_list):
        out = []
        for e in ex_list:
            evs = e.get(items_key, []) or []
            if any(any(k in v for k in kws) for v in evs) or any("一切" in v for v in evs):
                out.append({"name": e["name"], "level": e.get("level", ""),
                            "meaning": e.get("meaning", "")})
        return out

    support = _hit("yi", ann["ji_shen_explained"])     # 吉神之「宜」含此事
    against = _hit("ji", ann["xiong_sha_explained"])    # 凶煞之「忌」含此事

    net = sum(explain(s["name"])["weight"] for s in support) + \
          sum(explain(a["name"])["weight"] for a in against)   # 凶权为负

    if against and any(a["level"] in ("大凶", "凶") for a in against):
        verdict = f"此日有{ '、'.join(a['name'] for a in against[:3]) }等凶煞正忌{purpose}，不宜，另择为上。"
        level = "忌"
    elif support and not against:
        verdict = f"此日得{ '、'.join(s['name'] for s in support[:3]) }等吉神正利{purpose}，宜用。"
        level = "宜"
    elif support and against:
        verdict = f"此日吉凶交杂——{ '、'.join(s['name'] for s in support[:2]) }利之，然{ '、'.join(a['name'] for a in against[:2]) }忌之，须权衡或取吉时化解。"
        level = "参半"
    else:
        verdict = f"此日于{purpose}无显著吉神助、亦无大凶正忌，以建除黄道旺衰综合而断。"
        level = "平"

    return {
        "purpose": purpose,
        "support": support,
        "against": against,
        "net": round(net, 1),
        "level": level,
        "verdict": verdict,
        "shensha_annotated": ann,
    }
