def get_zao_full(men_zao_star: str, zhu_zao_star: str,
                 zao_mouth_star: str = "") -> Dict[str, Any]:
    """
    灶之完整断：灶座（主→灶为主、门→灶为辅）+ 灶口向。
    构成 512 门主灶局中「灶」的具体一环。
    """
    seat = ZAO_SEAT.get(zhu_zao_star, {})
    seat_men = ZAO_SEAT.get(men_zao_star, {})
    parts = [f"【灶座·主灶{zhu_zao_star}】{seat.get('d', '')}"]
    if seat_men:
        parts.append(f"【参·门灶{men_zao_star}】此灶对门得{men_zao_star}，{ZAO_MOUTH.get(men_zao_star, {}).get('d', '')}")
    mouth = {}
    if zao_mouth_star:
        mouth = ZAO_MOUTH.get(zao_mouth_star, {})
        parts.append(f"【灶口·向{zao_mouth_star}】{mouth.get('d', '')}")
    return {
        "quality": seat.get("q", "平"),
        "seat_level": seat.get("level", 0),
        "zhu_zao_star": zhu_zao_star,
        "men_zao_star": men_zao_star,
        "mouth_star": zao_mouth_star or None,
        "mouth_quality": mouth.get("q") if mouth else None,
        "desc": "　".join(parts),
        "principle": ZAO_PRINCIPLE,
    }


# 兼容旧接口名
def get_zao_judgment(men_zao_star: str, zhu_zao_star: str) -> Dict[str, Any]:
    return get_zao_full(men_zao_star, zhu_zao_star)


