def calculate_chenggu(year_gz: str, lunar_month: int, lunar_day: int, hour_zhi: str) -> Dict[str, Any]:
    """
    Calculate bone weight fortune.
    
    Args:
        year_gz: Year GanZhi (e.g. "庚午")
        lunar_month: Lunar month (1-12)
        lunar_day: Lunar day (1-30)
        hour_zhi: Hour DiZhi (e.g. "辰")
    """
    y_w = YEAR_WEIGHT.get(year_gz, 0.8)
    m_w = MONTH_WEIGHT.get(lunar_month, 0.8)
    d_w = DAY_WEIGHT.get(lunar_day, 0.8)
    h_w = HOUR_WEIGHT.get(hour_zhi, 0.8)
    
    total = round(y_w + m_w + d_w + h_w, 1)
    
    # Find closest verse
    verse_key = min(VERSE_TABLE.keys(), key=lambda k: abs(k - total))
    title, verse = VERSE_TABLE.get(verse_key, ("",""))
    
    # Fortune level
    if total >= 5.0:
        level = "上上"
        desc = "福禄丰盈，一生富贵"
    elif total >= 4.0:
        level = "中上"
        desc = "衣食无忧，福寿双全"
    elif total >= 3.5:
        level = "中等"
        desc = "平稳安康，勤俭持家"
    elif total >= 3.0:
        level = "中下"
        desc = "劳碌奔波，晚年转好"
    else:
        level = "下等"
        desc = "早年困苦，须靠自立"
    
    return {
        "total_weight": total,
        "year_weight": y_w,
        "month_weight": m_w,
        "day_weight": d_w,
        "hour_weight": h_w,
        "level": level,
        "level_desc": desc,
        "verse_title": title,
        "verse": verse,
        "breakdown": f"年{y_w}两 + 月{m_w}两 + 日{d_w}两 + 时{h_w}两 = {total}两",
    }
