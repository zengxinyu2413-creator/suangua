def get_aux_star(star: str, palace: str) -> str:
    for p in _norm_palace(palace):
        v = AUX_STAR_PALACE.get((star, p), "")
        if v:
            return v
    return ""


def interpret_aux_stars(palace_name: str,
                        minor_stars: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """解读某宫之辅煞星（六吉六煞禄存天马）。"""
    out = []
    for s in minor_stars:
        name = s.get("name", "")
        if name not in AUX_STAR_INFO:
            continue
        eff = get_aux_star(name, palace_name)
        out.append({
            "star": name,
            "lei": AUX_STAR_INFO[name]["lei"],
            "key": AUX_STAR_INFO[name]["key"],
            "nature": AUX_STAR_INFO[name]["nature"],
            "effect": eff,
        })
    return out


