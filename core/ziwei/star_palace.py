def _norm_palace(palace: str) -> List[str]:
    """宫名归一：表中宫名带/不带「宫」后缀不一（命宫带、余者不带），故两式皆试。"""
    p = (palace or "").strip()
    cands = [p]
    if p.endswith("宫"):
        cands.append(p[:-1])          # 官禄宫 → 官禄
    else:
        cands.append(p + "宫")        # 官禄 → 官禄宫
    # 别名（事业宫=官禄宫，交友宫=奴仆宫/迁移等惯称差异）
    _ALIAS = {"事业": "官禄", "事业宫": "官禄", "奴仆": "交友", "奴仆宫": "交友"}
    for c in list(cands):
        base = c[:-1] if c.endswith("宫") else c
        if base in _ALIAS:
            cands.append(_ALIAS[base])
    return cands


def get_star_palace(star: str, palace: str) -> str:
    """取某主星入某宫的断语（宫名带/不带「宫」皆兼容）。"""
    for p in _norm_palace(palace):
        v = STAR_PALACE.get((star, p), "")
        if v:
            return v
    return ""


def get_star_info(star: str) -> Dict[str, Any]:
    return STAR_INFO.get(star, {})


def interpret_palace_stars(palace_name: str,
                           major_stars: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    解读某宫所有主星（含庙旺调节）。
    major_stars: [{"name":..., "brightness":...}, ...]
    返回每颗主星的断语 + 庙旺调节。
    """
    out = []
    for s in major_stars:
        name = s.get("name", "")
        if name not in STAR_INFO:
            continue
        bright = (s.get("brightness") or "").strip()
        duan = get_star_palace(name, palace_name)
        if not duan:
            continue
        mod = BRIGHTNESS_MODIFIER.get(bright, {})
        out.append({
            "star": name,
            "brightness": bright,
            "info": STAR_INFO[name],
            "duan": duan,
            "brightness_tone": mod.get("tone", ""),
            "brightness_desc": mod.get("desc", ""),
        })
    return out


